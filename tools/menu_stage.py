"""Set the title screen in the Oval Plus infield.

    python tools/menu_stage.py

The menu's display kart drifts donuts around the origin, and its camera
orbits it there (scripts/menu.rhai). This copies Oval Plus's set dressing
and road into scenes/main_menu.scene.toml, moved so the origin lands on an
open stretch of the infield lawn: grandstands and the main straight on one
side, the park and its ring of hills on the other.

It writes:

- `splines/menu_stage.spline.toml`: the Oval Plus spline, moved.
- The block between `# >>> menu stage` and `# <<< menu stage` in the menu
  scene: the oval's dressing entities (terrain, merged chunks, signs, gantry,
  blimp) with their positions moved, and its road, walls and verges on the
  moved spline. Everything outside the block is left alone.
- `scripts/lib/menu_ground.rhai`: the lawn's heights under the kart's runs,
  read from the terrain model itself. Nothing in the dressing collides, so
  the menu can't raycast for the ground; menu.rhai sets its wheels on this.

Rerun it after `python tools/dress_track.py tracks/oval_plus.dress.toml`
so the menu keeps the oval's look. Nothing new is generated: the models are
the oval's own, so the web bundle doesn't grow.
"""

import os
import re
import tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "scenes", "oval_plus.scene.toml")
SPLINE = os.path.join(ROOT, "splines", "oval_plus.spline.toml")
MENU = os.path.join(ROOT, "scenes", "main_menu.scene.toml")
MENU_SPLINE = os.path.join(ROOT, "splines", "menu_stage.spline.toml")

# Where in Oval Plus the menu's origin sits: the middle of the infield lawn,
# 50 m in from the main straight and 45 m past the start line. The kart
# rides on the lawn and its straight runs reach ~30 m out before it swings
# back into its donut (menu.rhai); nothing stands within 29 m of here, and
# the lawn lies 0.6 m up (y lifts it to 0, give or take 0.25 m in 10 m and
# a metre at 30 m, which is why the kart reads the ground from menu_ground).
STAGE = (50.0, 0.6, -45.0)

MODELS = os.path.join(ROOT, "models")
GROUND = os.path.join(ROOT, "scripts", "lib", "menu_ground.rhai")
# How far out the kart's ground is kept: past its longest straight run
# (8 m/s for up to 3.5 s, from the 3 m donut). Beyond it the edge holds.
GROUND_REACH = 42.0

BEGIN = "# >>> menu stage"
END = "# <<< menu stage"

# Track entities to copy (track_path's track_info is left out: no race here)
TRACK = ["track_road", "track_wall_left", "track_wall_right",
         "track_verge_left", "track_verge_right"]


def fmt(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return f"{round(v, 3) + 0.0:g}"
    if isinstance(v, str):
        return f'"{v}"'
    if isinstance(v, list):
        return "[" + ", ".join(fmt(x) for x in v) + "]"
    raise TypeError(v)


def moved(p):
    return [p[0] - STAGE[0], p[1] - STAGE[1], p[2] - STAGE[2]]


def entity(name, comps):
    lines = [f"[entities.{name}]"]
    for cname, fields in comps.items():
        lines.append(f"[entities.{name}.{cname}]")
        lines += [f"{k} = {fmt(v)}" for k, v in fields.items()]
    return "\n".join(lines)


def write_spline():
    text = open(SPLINE, encoding="utf-8").read()

    def shift(m):
        x, y, z = (float(s) for s in m.group(1).split(","))
        return "position = " + fmt(moved([x, y, z]))

    body = re.sub(r"position = \[([^\]]*)\]", shift, text)
    head = ("# Generated by tools/menu_stage.py: splines/oval_plus.spline.toml\n"
            f"# moved by {fmt([-s for s in STAGE])} for the title screen. Edit\n"
            "# the oval's spline and rerun, never this file.\n\n")
    with open(MENU_SPLINE, "w", encoding="utf-8") as f:
        f.write(head + body)


def stage_block():
    with open(SOURCE, "rb") as f:
        ents = tomllib.load(f)["entities"]
    out = [
        BEGIN + ": generated by tools/menu_stage.py from scenes/oval_plus.scene.toml.",
        "# The Oval Plus infield, moved so the display kart drifts on its lawn.",
        "# Rerun the tool; hand edits here are replaced.",
        "",
    ]
    for name, comps in ents.items():
        # (the camera stage is the race camera's, and the menu has none)
        if not name.startswith("dress_") or "camera_stage" in comps:
            continue
        comps = {c: dict(f) for c, f in comps.items()}
        t = comps.setdefault("transform", {})
        t["position"] = moved(t.get("position", [0, 0, 0]))
        out += [entity(name, comps), ""]
    out += [entity("track_path", {"spline": {"file": "splines/menu_stage.spline.toml"}}), ""]
    for name in TRACK:
        out += [entity(name, ents[name]), ""]
    out.append(END)
    return "\n".join(out)


def write_menu():
    text = open(MENU, encoding="utf-8").read()
    block = stage_block()
    if BEGIN in text:
        a = text.index(BEGIN)
        b = text.index(END) + len(END)
        text = text[:a] + block + text[b:]
    else:
        text = text.rstrip("\n") + "\n\n\n" + block + "\n"
    with open(MENU, "w", encoding="utf-8") as f:
        f.write(text)


GROUND_FNS = """
// The lawn's height at (x, z): the terrain mesh's own surface. Each grid cell
// is two triangles split along its (+x, +z) diagonal, as dress_track.py
// builds it, so this matches the drawn ground exactly. Outside the grid the
// edge holds.
fn height(g, x, z) {
    let u = (x - g.x0) / g.step;
    let v = (z - g.z0) / g.step;
    let fu = floor(u);
    let fv = floor(v);
    let i = fu.to_int();
    let j = fv.to_int();
    if i < 0 { i = 0; u = 0.0; fu = 0.0; }
    if j < 0 { j = 0; v = 0.0; fv = 0.0; }
    if i > g.nx - 2 { i = g.nx - 2; u = 1.0; fu = 0.0; }
    if j > g.nz - 2 { j = g.nz - 2; v = 1.0; fv = 0.0; }
    let s = u - fu;
    let t = v - fv;
    let a = g.h[j * g.nx + i];
    let b = g.h[(j + 1) * g.nx + i];
    let c = g.h[j * g.nx + i + 1];
    let d = g.h[(j + 1) * g.nx + i + 1];
    if s + t <= 1.0 {
        a + (c - a) * s + (b - a) * t
    } else {
        d + (b - d) * (1.0 - s) + (c - d) * (1.0 - t)
    }
}
"""


def write_ground():
    """The lawn under the kart, from the terrain model the stage places."""
    import numpy as np
    import trimesh

    with open(SOURCE, "rb") as f:
        ents = tomllib.load(f)["entities"]
    t = ents["dress_terrain"]
    at = np.array(moved(t.get("transform", {}).get("position", [0, 0, 0])))
    mesh = trimesh.load(os.path.join(MODELS, t["model"]["asset"] + ".glb"),
                        force="mesh", process=False)
    V = np.asarray(mesh.vertices, dtype=np.float64) + at
    # the terrain is a regular grid: index each vertex by its column and row
    xs = np.unique(np.round(V[:, 0], 3))
    zs = np.unique(np.round(V[:, 2], 3))
    step = float(np.median(np.diff(xs)))
    H = np.full((len(zs), len(xs)), np.nan)
    H[np.searchsorted(zs, np.round(V[:, 2], 3)),
      np.searchsorted(xs, np.round(V[:, 0], 3))] = V[:, 1]
    ci = np.where(np.abs(xs) <= GROUND_REACH + step)[0]
    ri = np.where(np.abs(zs) <= GROUND_REACH + step)[0]
    H = H[ri[0]:ri[-1] + 1, ci[0]:ci[-1] + 1]
    assert not np.isnan(H).any(), "terrain is not a regular grid"
    nz, nx = H.shape
    rows = ",\n".join("        " + ", ".join(f"{h:.3f}" for h in row) for row in H)
    text = (
        "// menu_ground.rhai: generated by tools/menu_stage.py from\n"
        f"// models/{t['model']['asset']}.glb, as the menu stage places it. Rerun\n"
        "// the tool, never edit this file.\n"
        "//\n"
        "//     import \"menu_ground\" as menu_ground;\n"
        "//     let g = menu_ground::grid();          // once; keep it in a module let\n"
        "//     let y = menu_ground::height(g, x, z); // the lawn's surface there\n"
        "//\n"
        "// The title screen's lawn, sampled where the display kart drives\n"
        f"// (|x|, |z| up to {GROUND_REACH:g} m). Nothing in the dressing collides, so the\n"
        "// menu can't raycast for it.\n"
        "\n"
        "fn grid() {\n"
        f"    #{{ x0: {xs[ci[0]]:.3f}, z0: {zs[ri[0]]:.3f}, step: {step:.4f}, nx: {nx}, nz: {nz},\n"
        "      h: [\n" + rows + "\n      ] }\n"
        "}\n" + GROUND_FNS)
    with open(GROUND, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return H


if __name__ == "__main__":
    write_spline()
    write_menu()
    H = write_ground()
    print(f"menu stage: {os.path.relpath(MENU_SPLINE, ROOT)}, block in "
          f"{os.path.relpath(MENU, ROOT)}, lawn in {os.path.relpath(GROUND, ROOT)} "
          f"({H.shape[1]}x{H.shape[0]}, {H.min():.2f} to {H.max():.2f} m)")
