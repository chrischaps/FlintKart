def rgba(c, a):
    return (c[0], c[1], c[2], a)


def mix(a, b, t):
    return tuple(a[i] + (b[i] - a[i]) * t for i in range(3))


# ── Tiny TOML writer (keeps the output readable and diff-friendly) ──────

def fmt(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        s = f"{v:.3f}".rstrip("0")
        return s + "0" if s.endswith(".") else s
    if isinstance(v, str):
        return f'"{v}"'
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(fmt(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{k} = {fmt(x)}" for k, x in v.items()) + " }"
    raise TypeError(v)


def f(*xs):
    """Force floats, so TOML never reads 1 where an f32 is meant."""
    return tuple(float(x) for x in xs)


def keys(*pairs, interp=None):
    """Curve from (t, value) pairs."""
    d = {"keys": [{"t": float(t), "v": v} for t, v in pairs]}
    if interp:
        d["interp"] = interp
    return d


def size(*pairs, interp="smooth"):
    return keys(*[(t, f(s, s) if not isinstance(s, tuple) else f(*s)) for t, s in pairs], interp=interp)


def write_effect(name, doc, emitters, seed, budget=None):
    lines = [f"# {name}.particles.toml — generated by tools/generate_fx.py; edit the generator.",
             f"# {doc}", "",
             f'name = "{name}"', f"seed = {seed}"]
    if budget:
        lines.append(f"budget = {budget}")
    for em in emitters:
        lines.append("")
        lines.append("[[emitters]]")
        forces = em.pop("forces", [])
        bursts = em.pop("bursts", [])
        shape = em.pop("shape", None)
        for k, v in em.items():
            lines.append(f"{k} = {fmt(v)}")
        if shape:
            lines.append("")
            lines.append("[emitters.shape]")
            for k, v in shape.items():
                lines.append(f"{k} = {fmt(v)}")
        for b in bursts:
            lines.append("")
            lines.append("[[emitters.bursts]]")
            for k, v in b.items():
                lines.append(f"{k} = {fmt(v)}")
        for fo in forces:
            lines.append("")
            lines.append("[[emitters.forces]]")
            for k, v in fo.items():
                lines.append(f"{k} = {fmt(v)}")
    path = os.path.join(OUT_DIR, f"{name}.particles.toml")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    return path


def one_shot(em, count, at=0.0):
    """Burst-only emitter that stops itself, so a play_effect instance ends."""
    em.update({
        "emission_rate": 0.0,
        "duration": 0.05 + at,
        "looping": False,
    })
    em["bursts"] = [{"time": float(at), "count": count}]
    return em


# ── Sprite textures ─────────────────────────────────────────────────────
#
# White sprites the particle colour tints. Kept chunky and toy-like: hard
# enough edges to read as paper, puffs and stars rather than generic glow.

TEX = 128


def _grid():
    c = (np.arange(TEX) + 0.5) / TEX * 2.0 - 1.0  # -1..1
    x, y = np.meshgrid(c, c)
    return x, y


def _smooth(edge0, edge1, v):
    t = np.clip((v - edge0) / (edge1 - edge0), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def _save(name, rgb, alpha):
    rgb = np.clip(rgb, 0.0, 1.0)
    alpha = np.clip(alpha, 0.0, 1.0)
    img = np.dstack([rgb, rgb, rgb, alpha]) if rgb.ndim == 2 else np.dstack([rgb, alpha])
    path = os.path.join(ROOT, name)
    Image.fromarray((img * 255.0 + 0.5).astype(np.uint8), "RGBA").save(path)
    return path


def tex_paper():
    """A paper scrap with a centre crease: one half catches the light."""
    x, y = _grid()
    edge = 1.0 - np.maximum(np.abs(x), np.abs(y))
    alpha = _smooth(0.0, 0.05, edge)
    shade = np.where(x < 0.0, 1.0, 0.8) - 0.06 * (y + 1.0) * 0.5
    return _save(T_PAPER, shade, alpha)


def tex_puff():
    """A lumpy cartoon cloud: five overlapping balls, lighter at the core."""
    x, y = _grid()
    balls = [(0.0, 0.0, 0.58), (-0.36, 0.18, 0.4), (0.38, 0.16, 0.42),
             (-0.12, -0.38, 0.4), (0.22, -0.34, 0.38), (0.05, 0.42, 0.36)]
    field = np.zeros_like(x)
    for bx, by, r in balls:
        d = np.sqrt((x - bx) ** 2 + (y - by) ** 2) / r
        field = np.maximum(field, 1.0 - d)
    alpha = _smooth(0.0, 0.16, field) * 0.95
    r = np.sqrt(x * x + y * y)
    shade = 1.0 - 0.22 * np.clip(r / 0.9, 0.0, 1.0) ** 1.5
    return _save(T_PUFF, shade, alpha)


def tex_spark():
    """A hot pinpoint: a white core with a short, steep falloff."""
    x, y = _grid()
    r = np.sqrt(x * x + y * y)
    alpha = np.clip(1.0 - r, 0.0, 1.0) ** 2.2
    core = np.exp(-(r / 0.22) ** 2)
    return _save(T_SPARK, 0.85 + 0.15 * core, np.clip(alpha + core * 0.4, 0.0, 1.0))


def tex_star():
    """A four-point twinkle with a round heart."""
    x, y = _grid()
    r = np.sqrt(x * x + y * y)
    arms = np.maximum(np.exp(-(x / 0.07) ** 2) * (1.0 - np.abs(y)),
                      np.exp(-(y / 0.07) ** 2) * (1.0 - np.abs(x)))
    heart = np.exp(-(r / 0.28) ** 2)
    alpha = np.clip(arms ** 1.3 + heart, 0.0, 1.0)
    return _save(T_STAR, np.ones_like(x), alpha)


def tex_ring():
    """A shock ring: a bright rim and a faint fill."""
    x, y = _grid()
    r = np.sqrt(x * x + y * y)
    rim = np.exp(-((r - 0.8) / 0.08) ** 2)
    fill = 0.12 * _smooth(0.9, 0.6, r)
    return _save(T_RING, np.ones_like(x), np.clip(rim + fill, 0.0, 1.0))


