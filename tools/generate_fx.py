#!/usr/bin/env python3
"""Generate FlintKart's particle effects (particles/*.particles.toml).

Every effect is built from the glow-up palette (docs/glow-up.md), so drift
tiers, boost flames, item bursts and the finish confetti all speak the same
seven colours. Re-run after changing the palette or a recipe:

    python tools/generate_fx.py

Kart-local axes (the kart prefab's root): +X right, +Y up, +Z toward the
tail (tail lights sit at z = +1.28, rear wheels at x = +-0.73, z = 0.85).
The kart's origin sits on the road surface. Effects attached to the kart
(`particle_effect` children in prefabs/kart.prefab.toml) idle at
`emission_scale = 0` and are opened up by scripts/kart_fx.rhai; one-shot
effects are spawned with `play_effect` at a world position.
"""

